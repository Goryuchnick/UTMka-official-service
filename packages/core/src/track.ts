/**
 * Аналитика: перечень целевых действий и контракт отправки.
 *
 * Зачем это в ядре, а не в приложении. Счётчик стоит только в вебе, но список
 * действий — продуктовое знание, а не свойство браузера: «человек скопировал
 * ссылку» одинаково значимо в окне и во вкладке. Держать перечень в `apps/web`
 * значило бы, что десктоп о своих же ключевых действиях не знает, а имена целей
 * разъедутся с именами кнопок при первой правке.
 *
 * Почему отдельный экспорт оболочки, а не поле `UtmkaBackend`: к данным
 * отношения не имеет — как и `saveFile`, это способность окружения. В вебе
 * `track` уходит в Яндекс.Метрику, в окне Tauri — в пустоту (счётчика там нет
 * и не будет: приложение работает офлайн и обещает не ходить в сеть само).
 *
 * ⚠️ Что сюда НЕЛЬЗЯ класть. Ни адресов, ни значений меток, ни кодовой фразы —
 * ровно по той же причине, по которой в счётчике выключен вебвизор
 * (см. `apps/web/components/Metrika.tsx`). В полях инструмента живут реальные
 * кампании пользователя. Поэтому параметры события ограничены типом
 * `TrackParams`, а не оставлены свободным словарём: свободный словарь рано или
 * поздно унесёт туда `url`, и обещание «мы о вас ничего не собираем» станет
 * неправдой молча.
 */

/**
 * Целевое действие. Не «клик по кнопке», а «получено то, ради чего пришли»:
 * скопированная ссылка — результат, открытый экран — нет.
 *
 * Имена совпадают с идентификаторами целей в счётчике 111529339, потому что
 * это одно и то же понятие в двух местах. Переименование — только парой:
 * здесь и в Метрике, иначе цель тихо перестанет достигаться.
 */
export type TrackEvent =
  /** Готовая ссылка ушла в буфер — главное целевое действие генератора. */
  | 'link_copied'
  /** Пакет собран: таблица превратилась в ссылки. */
  | 'batch_done'
  /** Чужая ссылка разобрана на метки. */
  | 'parse_done'
  /** Сделана короткая ссылка через clck.ru. */
  | 'short_made'
  /** QR-код выгружен в файл (SVG или PNG). */
  | 'qr_saved'
  /** Шаблон сохранён — человек собирается вернуться. */
  | 'template_saved'
  /** Помощник ответил бриф-запросом. */
  | 'assistant_used'
  /** Заведена кодовая фраза — единственная форма «регистрации». */
  | 'passphrase_created'
  /** Уход в версию для компьютера: зов из веба в десктоп. */
  | 'desktop_click'

/**
 * Человеческие имена целей — то, что видно в отчётах Метрики.
 *
 * Лежат рядом с ключами, чтобы цель в панели и вызов в коде заводились из
 * одного места: скрипт `scripts/analytics_goals.py` читает этот файл и
 * создаёт недостающие цели, а не сверяется с памятью автора.
 */
export const TRACK_EVENT_NAMES: Record<TrackEvent, string> = {
  link_copied: 'Скопирована ссылка',
  batch_done: 'Собран пакет ссылок',
  parse_done: 'Разобрана чужая ссылка',
  short_made: 'Сделана короткая ссылка',
  qr_saved: 'Выгружен QR-код',
  template_saved: 'Сохранён шаблон',
  assistant_used: 'Ответил помощник',
  passphrase_created: 'Заведена кодовая фраза',
  desktop_click: 'Переход к версии для компьютера',
}

/**
 * Параметры события — закрытый список, а не свободный словарь.
 *
 * Здесь только `size`: размер пакета, округлённый до корзины. Точное число
 * строк ничего не добавляет к решению, а различать пакет в 3 ссылки и в 300
 * нужно — это разные пользователи.
 *
 * Площадки в параметрах нет намеренно: у каждой посадочной свой адрес
 * (`/tilda`, `/vk`), и разрез «цель по странице входа» в отчёте отвечает на
 * тот же вопрос, не требуя тащить лишнее состояние через экраны.
 */
export interface TrackParams {
  size?: '1-10' | '11-50' | '51-200' | '200+'
}

/** Корзина размера пакета: сырое число наружу не отдаём. */
export function sizeBucket(count: number): NonNullable<TrackParams['size']> {
  if (count <= 10) return '1-10'
  if (count <= 50) return '11-50'
  if (count <= 200) return '51-200'
  return '200+'
}

/**
 * Отправка события. Ничего не возвращает и не бросает: аналитика не имеет
 * права уронить действие пользователя или заставить экран его ждать.
 */
export type Track = (event: TrackEvent, params?: TrackParams) => void
