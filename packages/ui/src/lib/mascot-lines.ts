/** Счётчики обхода: у каждого события своя очередь. */
const cursor = new Map<Event, number>()

const TONES: Partial<Record<Event, MascotTone>> = {
  redirectLost: 'alert',
  cleared: 'neutral',
  removed: 'neutral',
}

/** Сказать про событие. Реплики идут по кругу, не повторяясь подряд. */
export function sayAbout(event: Event): void {
  const lines = LINES[event]
  const index = cursor.get(event) ?? 0
  cursor.set(event, (index + 1) % lines.length)
  flashMascot(lines[index] ?? lines[0] ?? '', TONES[event] ?? 'done')
}
