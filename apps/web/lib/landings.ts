export function getLanding(slug: string): Landing | undefined {
  return LANDINGS.find((landing) => landing.slug === slug)
}

/** Пресет посадочной — если он у неё есть. */
export function landingPreset(landing: Landing): Preset | undefined {
  return landing.presetId ? getPreset(landing.presetId) : undefined
}

/** Соседние пресеты площадки: реклама рядом с постом, канал рядом с кабинетом. */
export function landingAlsoPresets(landing: Landing): Preset[] {
  return (landing.alsoPresetIds ?? [])
    .map((id) => getPreset(id))
    .filter((preset): preset is Preset => preset !== undefined)
}
