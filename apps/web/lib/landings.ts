/**
 * Тексты посадочных страниц и главной.
 *
 * Зачем посадочные есть. Главная отвечает на запрос «конструктор UTM», но люди
 * ищут площадку: «utm для директа», «utm метки тильда». Такой запрос выигрывает
 * страница, у которой площадка стоит в заголовке и в тексте, а генератор открыт
 * уже с её метками. Одна страница пятью запросами не ранжируется.
 *
 * Почему это не дорвеи: страницы отличаются не абзацем текста, а поведением —
 * на каждой генератор предзаполнен своим пресетом, и разбор ошибок свой.
 *
 * Текст площадки живёт в `@utmka/core` (`explain`, `placeholders`, `caveat`) и
 * сюда не копируется: правило площадки обязано совпадать в вебе, в десктопе и
 * на посадочной. Здесь — только то, чего в ядре нет: заголовки, поисковый
 * запрос, вопросы и ответы.
 */

import { getPreset, type Preset } from '@utmka/core'

/** Блок текста под генератором. Либо абзацы, либо список «термин — что с ним». */
export interface LandingSection {
  title: string
  paragraphs?: readonly string[]
  bullets?: readonly { term: string; text: string }[]
}

export interface Landing {
  /** Адрес страницы: `/yandex-direct`. */
  slug: string
  /** Пресет площадки — им предзаполняется генератор. У Тильды пресета нет. */
  presetId?: string
  /**
   * Соседние пресеты той же площадки: у ВК реклама и пост — разный тип
   * трафика, и путают их постоянно. Показываем рядом, а не заводим страницу
   * под каждый: запрос-то один.
   */
  alsoPresetIds?: readonly string[]
  /** Короткое имя для перелинковки между посадочными. */
  short: string
  /** Заголовок страницы. Он же H1 — второго заголовка первого уровня нет. */
  h1: string
  /** SEO-title, отличается от H1: в нём есть слово, которое люди набирают. */
  title: string
  description: string
  keywords: readonly string[]
  /** Два предложения под заголовком: что здесь и кому. */
  lead: string
  sections: readonly LandingSection[]
  faq: readonly { q: string; a: string }[]
  /** Пример готовой ссылки — показываем разметкой, а не картинкой. */
  example?: { base: string; params: readonly (readonly [string, string])[] }
}

